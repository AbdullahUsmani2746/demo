import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";

export function generateProductionPlanPDF(reportData, session, company) {
  const { plans = [], materials = [], totalQty = 0 } = reportData;

  const doc = new jsPDF({
    orientation: "portrait",
    unit: "mm",
    format: "a4",
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();

  const primaryColor = [139, 0, 0];
  const headerBg = [128, 0, 32];
  const lightGray = [245, 245, 245];
  const borderColor = [180, 180, 180];

  // ─── HEADER ───────────────────────────────────────────────────────────────
  // Company name
  doc.setFillColor(...headerBg);
  doc.rect(10, 8, pageWidth - 20, 10, "F");

  doc.setFontSize(13);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(255, 255, 255);
  const companyName =
    company?.company || company?.name || session?.user?.company || "Company";
  doc.text(companyName, pageWidth / 2, 15, { align: "center" });

  // Report title
  doc.setFontSize(11);
  doc.setTextColor(...primaryColor);
  doc.setFont("helvetica", "bold");
  doc.text("RAW MATERIAL REQUIRED", pageWidth / 2, 24, { align: "center" });

  // Underline
  doc.setDrawColor(...primaryColor);
  doc.setLineWidth(0.5);
  doc.line(10, 26, pageWidth - 10, 26);

  // Date and page info
  const now = new Date();
  const dateStr = now.toLocaleDateString("en-GB", {
    day: "2-digit",
    month: "2-digit",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  });

  doc.setFontSize(8);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(80, 80, 80);
  doc.text(dateStr, 12, 31);
  doc.text("Page 1 of 1", pageWidth - 12, 31, { align: "right" });

  // ─── MAIN TABLE ──────────────────────────────────────────────────────────
  const tableStartY = plans.length > 0 ? 40 : 33;

  const tableBody = materials.map((mat, idx) => [
    mat.material_id,
    mat.rm_item || "N/A",
    mat.qty_req % 1 === 0 ? mat.qty_req.toFixed(2) : mat.qty_req.toFixed(2),
  ]);

  // Total row
  tableBody.push([
    {
      content: "Total:",
      colSpan: 2,
      styles: { fontStyle: "bold", halign: "right" },
    },
    {
      content: totalQty.toFixed(2),
      styles: { fontStyle: "bold", halign: "right" },
    },
  ]);

  autoTable(doc, {
    startY: tableStartY,
    head: [
      [
        { content: "Material Id", styles: { halign: "left" } },
        { content: "RM Item", styles: { halign: "left" } },
        { content: "Qty Req", styles: { halign: "right" } },
      ],
    ],
    body: tableBody,
    theme: "grid",
    headStyles: {
      fillColor: primaryColor,
      textColor: [255, 255, 255],
      fontStyle: "bold",
      fontSize: 9,
      cellPadding: 3,
    },
    bodyStyles: {
      fontSize: 8.5,
      cellPadding: 2.5,
      textColor: [30, 30, 30],
    },
    alternateRowStyles: {
      fillColor: lightGray,
    },
    columnStyles: {
      0: { cellWidth: 28, halign: "left", fontStyle: "bold" },
      1: { cellWidth: "auto", halign: "left" },
      2: { cellWidth: 25, halign: "right" },
    },
    margin: { left: 10, right: 10 },
    tableWidth: pageWidth - 20,
    didDrawCell: (data) => {
      // Highlight total row differently
      if (data.row.index === tableBody.length - 1 && data.section === "body") {
        doc.setFillColor(220, 220, 220);
      }
    },
    styles: {
      lineColor: borderColor,
      lineWidth: 0.3,
    },
  });

  // ─── FOOTER ──────────────────────────────────────────────────────────────
  const finalY = doc.lastAutoTable.finalY || tableStartY + 20;
  const footerY = Math.max(finalY + 10, pageHeight - 20);

  doc.setDrawColor(...borderColor);
  doc.setLineWidth(0.3);
  doc.line(10, footerY, pageWidth - 10, footerY);

  doc.setFontSize(7.5);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(120, 120, 120);
  doc.text(`Generated by: ${session?.user?.name || "System"}`, 12, footerY + 5);
  doc.text(
    `Total Materials: ${materials.length}`,
    pageWidth - 12,
    footerY + 5,
    {
      align: "right",
    },
  );

  return doc;
}

/**
 * Generate simple Production Plan summary PDF (list of plans)
 */
export function generateProductionPlanListPDF(plans, session, company) {
  const doc = new jsPDF({
    orientation: "portrait",
    unit: "mm",
    format: "a4",
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const primaryColor = [139, 0, 0];

  // Header
  doc.setFillColor(220, 20, 60);
  doc.rect(10, 8, pageWidth - 20, 10, "F");
  doc.setFontSize(12);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(255, 255, 255);
  doc.text(company?.company || company?.name || "Company", pageWidth / 2, 15, {
    align: "center",
  });

  doc.setFontSize(11);
  doc.setTextColor(...primaryColor);
  doc.text("PRODUCTION PLAN", pageWidth / 2, 24, { align: "center" });

  doc.setDrawColor(...primaryColor);
  doc.setLineWidth(0.5);
  doc.line(10, 26, pageWidth - 10, 26);

  // Date
  doc.setFontSize(8);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(80, 80, 80);
  doc.text(new Date().toLocaleDateString("en-GB"), 12, 31);

  const tableBody = plans.map((plan) => [
    plan.id,
    plan.finished_id || "N/A",
    plan.product_name || "N/A",
    plan.qty ? plan.qty.toFixed(2) : "0.00",
    plan.status || "Pending",
    plan.sale_ord_no || "-",
    plan.dated ? new Date(plan.dated).toLocaleDateString("en-GB") : "-",
  ]);

  autoTable(doc, {
    startY: 35,
    head: [["Plan ID", "MM No", "Product", "Qty", "Status", "SO#", "Date"]],
    body: tableBody,
    theme: "grid",
    headStyles: {
      fillColor: primaryColor,
      textColor: [255, 255, 255],
      fontStyle: "bold",
      fontSize: 8,
      cellPadding: 2.5,
    },
    bodyStyles: { fontSize: 8, cellPadding: 2 },
    alternateRowStyles: { fillColor: [245, 245, 245] },
    columnStyles: {
      0: { cellWidth: 16 },
      1: { cellWidth: 20 },
      2: { cellWidth: "auto" },
      3: { cellWidth: 18, halign: "right" },
      4: { cellWidth: 22 },
      5: { cellWidth: 18 },
      6: { cellWidth: 22 },
    },
    margin: { left: 10, right: 10 },
  });

  return doc;
}
