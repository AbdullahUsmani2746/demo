// Excel and PDF of the wide report table (CLAUDE.md rule 15). Both read the
// export model WideTable hands out (getExportModel), so paper shows what the
// screen shows.
//
// Excel: "Current view" or "Everything"; filters listed at the top, the column
// group band as a merged header row, panes frozen on the pinned columns and
// the header, subtotals / totals as SUBTOTAL formulas.
// PDF: the current view; landscape above 10 columns, A3 above 16; when it is
// still too wide the columns split across pages and the pinned columns repeat;
// text never goes below 7pt.
import { formatValue, getReportDisplay, isNumericCol, numberKind, rawValue } from "./layout";

const MAROON = "FF800000";
const MAROON_RGB = [128, 0, 0];

// Excel number format from the user's Display settings: lakh (12,34,567) or
// international grouping, 2 decimals or none, negatives -1,200 or (1,200).
const numFmtOf = (col) => {
  if (col.type === "percent" || col.type === "percentage") return '0.00"%"';
  const d = getReportDisplay();
  const dec = col.type === "currency" ? (d.decimals ? ".00" : "") : ".###";
  if (d.grouping === "lakh") {
    // Excel allows two conditions: crore and lakh groups, then the rest.
    return `[>=10000000]##\\,##\\,##\\,##0${dec};[>=100000]##\\,##\\,##0${dec};##,##0${dec}`;
  }
  const pos = `#,##0${dec}`;
  return `${pos};[Red]${d.brackets ? `(${pos})` : `-${pos}`}`;
};
// The user's "Make bold" choice for a number column.
const isBoldNumber = (col) => {
  const kind = numberKind(col);
  return !!(kind && getReportDisplay().bold[kind]);
};

const colLetter = (n) => {
  let s = "";
  let x = n;
  while (x > 0) {
    const m = (x - 1) % 26;
    s = String.fromCharCode(65 + m) + s;
    x = Math.floor((x - 1) / 26);
  }
  return s;
};

// Band runs over the export columns (pinned columns never sit under a band).
function bandsOf(model) {
  const out = [];
  model.columns.forEach((c, i) => {
    const g = i < model.pinnedCount ? null : model.groupOf(c.key);
    const last = out[out.length - 1];
    if (last && last.group === g && g) last.span++;
    else out.push({ group: g, span: 1, start: i });
  });
  return out;
}

const cellNumber = (col, row) => {
  const n = Number(rawValue(col, row));
  return Number.isFinite(n) ? n : 0;
};
const cellPlain = (col, row) => {
  const v = rawValue(col, row);
  if (col.type === "date") return formatValue(col, v);
  if (v === null || v === undefined || typeof v === "object") return Array.isArray(v) ? v.join(", ") : "";
  return v;
};

export async function exportWideExcel(model, meta) {
  const { default: ExcelJS } = await import("exceljs");
  const wb = new ExcelJS.Workbook();
  wb.creator = meta.userName || "ERP";
  const ws = wb.addWorksheet("Report");
  const cols = model.columns;
  const n = cols.length || 1;
  const bands = bandsOf(model);
  const hasBands = bands.some((b) => b.group);

  let r = 1;
  const fullRow = (text, style) => {
    if (n > 1) ws.mergeCells(r, 1, r, n);
    const c = ws.getCell(r, 1);
    c.value = text;
    Object.assign(c, style);
    r++;
  };
  fullRow(meta.companyName || "", { font: { bold: true, size: 15, color: { argb: "FFFFFFFF" } }, fill: { type: "pattern", pattern: "solid", fgColor: { argb: MAROON } }, alignment: { vertical: "middle" } });
  ws.getRow(r - 1).height = 24;
  fullRow(`${meta.title} — ${model.viewLabel}`, { font: { bold: true, size: 12 } });
  fullRow(`Generated by ${meta.userName || "System"} on ${meta.generatedAt}`, { font: { italic: true, size: 9, color: { argb: "FF666666" } } });
  (meta.filters || []).forEach((f) => fullRow(`${f.label}: ${f.value}`, { font: { size: 10 } }));
  r++; // spacer

  const headStyle = (cell, center) => {
    cell.font = { bold: true, color: { argb: "FFFFFFFF" }, size: 10 };
    cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: MAROON } };
    cell.alignment = { horizontal: center ? "center" : "left", vertical: "middle", wrapText: true };
    cell.border = { left: { style: "thin", color: { argb: "FFB36666" } }, bottom: { style: "thin", color: { argb: "FFB36666" } } };
  };
  const headerTop = r;
  if (hasBands) {
    bands.forEach((b) => {
      const c1 = b.start + 1;
      if (b.group) {
        if (b.span > 1) ws.mergeCells(r, c1, r, c1 + b.span - 1);
        const cell = ws.getCell(r, c1);
        cell.value = b.group.label.toUpperCase();
        headStyle(cell, true);
      } else {
        // ungrouped column: its name spans both header rows
        for (let k = 0; k < b.span; k++) {
          ws.mergeCells(r, c1 + k, r + 1, c1 + k);
          const cell = ws.getCell(r, c1 + k);
          cell.value = cols[b.start + k].exportHeader || cols[b.start + k].headerName;
          headStyle(cell, false);
        }
      }
    });
    r++;
  }
  cols.forEach((c, i) => {
    const cell = ws.getCell(r, i + 1);
    if (hasBands && !(i >= model.pinnedCount && model.groupOf(c.key))) return; // merged from the band row
    cell.value = c.exportHeader || c.headerName;
    headStyle(cell, isNumericCol(c));
    if (isNumericCol(c)) cell.alignment = { ...cell.alignment, horizontal: "right" };
  });
  const headerBottom = r;
  r++;

  const firstData = r;
  const subRows = [];
  const formulas = model.formulas !== false;
  model.items.forEach((it) => {
    // Grouped document header (layout.groupRows headerFields): its own values
    // in their columns, the label in the first column when that one is not a
    // header field.
    if (it.type === "group" && it.fields) {
      const row = ws.getRow(r);
      row.font = { bold: true, color: { argb: MAROON } };
      cols.forEach((col, i) => {
        const cell = row.getCell(i + 1);
        cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FFF7ECEC" } };
        if (it.fields.has(col.key)) {
          if (isNumericCol(col)) {
            cell.value = cellNumber(col, it.row);
            cell.numFmt = numFmtOf(col);
          } else cell.value = `${i === 0 ? "  ".repeat(it.depth) : ""}${cellPlain(col, it.row) ?? ""}`;
        } else if (i === 0) cell.value = `${"  ".repeat(it.depth)}${it.label} · ${it.count}`;
      });
      it._start = r + 1;
      r++;
      return;
    }
    if (it.type === "group") {
      if (n > 1) ws.mergeCells(r, 1, r, n);
      const c = ws.getCell(r, 1);
      c.value = `${"  ".repeat(it.depth)}${it.label} · ${it.count}`;
      c.font = { bold: true, color: { argb: MAROON } };
      c.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FFF7ECEC" } };
      it._start = r + 1;
      r++;
      return;
    }
    if (it.type === "sub") {
      subRows.push(r);
      const row = ws.getRow(r);
      row.font = { bold: true };
      cols.forEach((col, i) => {
        const cell = row.getCell(i + 1);
        cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FFF1F1F1" } };
        if (i === 0) cell.value = it.label;
        else if (it.totals[col.key] !== undefined) {
          const v = it.totals[col.key];
          // A plain sum becomes a formula over the group's rows; rates and
          // "last" balances stay values. A folded group has no rows here, so
          // its subtotal is the value — outer SUBTOTALs add it (they skip
          // only other SUBTOTAL cells), so totals above it stay right.
          const groupStart = findGroupStart(model.items, it);
          const hasRows = groupStart && groupStart <= r - 1;
          cell.value = formulas && !it.fromServer && col.showTotal && col.totalType !== "last" && !col.totalRatio && hasRows
            ? { formula: `SUBTOTAL(9,${colLetter(i + 1)}${groupStart}:${colLetter(i + 1)}${r - 1})`, result: v }
            : v;
          cell.numFmt = numFmtOf(col);
        }
      });
      r++;
      return;
    }
    const row = ws.getRow(r);
    if (it.extra === "total") row.font = { bold: true };
    cols.forEach((col, i) => {
      const cell = row.getCell(i + 1);
      if (isNumericCol(col)) {
        cell.value = cellNumber(col, it.row);
        cell.numFmt = numFmtOf(col);
        if (isBoldNumber(col)) cell.font = { bold: true };
      } else {
        cell.value = cellPlain(col, it.row);
      }
    });
    r++;
  });
  const lastData = r - 1;

  if (model.hasTotals && lastData >= firstData) {
    const row = ws.getRow(r);
    row.font = { bold: true, color: { argb: "FFFFFFFF" } };
    cols.forEach((col, i) => {
      const cell = row.getCell(i + 1);
      cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: MAROON } };
      if (i === 0) cell.value = "TOTAL";
      else if (model.totals[col.key] !== undefined) {
        const v = model.totals[col.key];
        cell.value = formulas && col.showTotal && col.totalType !== "last" && !col.totalRatio
          ? { formula: `SUBTOTAL(9,${colLetter(i + 1)}${firstData}:${colLetter(i + 1)}${lastData})`, result: v }
          : v;
        cell.numFmt = numFmtOf(col);
      }
    });
  }

  // Widths and frozen panes (pinned columns + header).
  cols.forEach((c, i) => {
    const w = Math.max(String(c.headerName || "").length + 2, isNumericCol(c) ? 12 : c.type === "date" ? 12 : 16);
    ws.getColumn(i + 1).width = Math.min(w, i < model.pinnedCount ? 40 : 30);
  });
  ws.views = [{ state: "frozen", xSplit: model.pinnedCount, ySplit: headerBottom, topLeftCell: `${colLetter(model.pinnedCount + 1)}${headerBottom + 1}` }];
  ws.autoFilter = { from: { row: headerBottom, column: 1 }, to: { row: headerBottom, column: n } };
  void headerTop;
  void subRows;

  const buf = await wb.xlsx.writeBuffer();
  const blob = new Blob([buf], { type: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet" });
  const a = document.createElement("a");
  a.href = URL.createObjectURL(blob);
  a.download = `${meta.fileBase}.xlsx`;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(a.href), 4000);
}

// The sheet row where a subtotal's data starts: the row after its group header.
function findGroupStart(items, sub) {
  const gid = sub.id.replace(/\/sub$/, "");
  const g = items.find((x) => x.type === "group" && x.id === gid);
  return g?._start || null;
}

// ── PDF ─────────────────────────────────────────────────────────────────────
const MIN_PT = 7;

export async function exportWidePdf(model, meta) {
  const { jsPDF } = await import("jspdf");
  const { default: autoTable } = await import("jspdf-autotable");
  const cols = model.columns;
  const n = cols.length;
  const format = n > 16 ? "a3" : "a4";
  const orientation = n > 10 ? "landscape" : "portrait";
  const doc = new jsPDF({ orientation, unit: "mm", format, putOnlyUsedFonts: true });
  const pageW = doc.internal.pageSize.getWidth();
  const margin = 8;
  const avail = pageW - margin * 2;
  const opts = { amounts: model.amounts };

  // Width a column needs at a font size: longest text in a sample of rows.
  const dataRows = model.items.filter((i) => i.type === "row").map((i) => i.row);
  const step = Math.max(1, Math.floor(dataRows.length / 300));
  const chars = cols.map((c) => {
    let m = String(c.headerName || "").length * 0.8;
    for (let i = 0; i < dataRows.length; i += step) {
      const t = isNumericCol(c) ? formatValue(c, rawValue(c, dataRows[i]), opts) : String(cellPlain(c, dataRows[i]) ?? "");
      if (t.length > m) m = t.length;
    }
    // subtotals too — all a folded group prints
    if (isNumericCol(c)) {
      for (const it of model.items) {
        if (it.type !== "sub" || it.totals?.[c.key] === undefined) continue;
        const t = formatValue(c, it.totals[c.key], opts);
        if (t.length > m) m = t.length;
      }
    }
    return Math.min(m, isNumericCol(c) ? 18 : 36);
  });
  const widthAt = (pt, i) => chars[i] * pt * 0.2 + 3; // ~0.2mm per char per pt + padding
  const fitsAt = (pt, idx) => idx.reduce((a, i) => a + widthAt(pt, i), 0) <= avail;

  const all = cols.map((_, i) => i);
  let pt = 8;
  if (!fitsAt(8, all)) pt = fitsAt(7.5, all) ? 7.5 : MIN_PT;

  // Column sets: everything if it fits, else pinned + as many as fit, repeated.
  const pinnedIdx = all.slice(0, model.pinnedCount);
  const rest = all.slice(model.pinnedCount);
  const sets = [];
  if (fitsAt(pt, all)) sets.push(all);
  else {
    let cur = [];
    rest.forEach((i) => {
      if (cur.length && !fitsAt(pt, [...pinnedIdx, ...cur, i])) {
        sets.push([...pinnedIdx, ...cur]);
        cur = [];
      }
      cur.push(i);
    });
    if (cur.length) sets.push([...pinnedIdx, ...cur]);
  }

  const banner = () => {
    doc.setFillColor(...MAROON_RGB);
    doc.rect(0, 0, pageW, 16, "F");
    doc.setTextColor(255, 255, 255);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(12);
    doc.text(meta.companyName || "", margin, 7);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8.5);
    doc.text(`${meta.title} — ${model.viewLabel}`, margin, 12.5);
    doc.setFontSize(7.5);
    doc.text(meta.generatedAt, pageW - margin, 7, { align: "right" });
    doc.text(`${dataRows.length} row(s)`, pageW - margin, 12.5, { align: "right" });
  };

  const bodyFor = (idx) =>
    model.items.map((it) => {
      if (it.type === "group" && it.fields) {
        return idx.map((i, k) => {
          const c = cols[i];
          let content = "";
          if (it.fields.has(c.key)) content = isNumericCol(c) ? formatValue(c, rawValue(c, it.row), opts) : String(cellPlain(c, it.row) ?? "");
          else if (k === 0) content = `${it.label} · ${it.count}`;
          return { content: k === 0 ? `${"  ".repeat(it.depth)}${content}` : content, _kind: "group" };
        });
      }
      if (it.type === "group") return [{ content: `${"  ".repeat(it.depth)}${it.label} · ${it.count}`, colSpan: idx.length, _kind: "group" }];
      if (it.type === "sub") {
        return idx.map((i, k) => {
          const c = cols[i];
          if (k === 0) return { content: it.label, _kind: "sub" };
          const v = it.totals[c.key];
          return { content: v === undefined ? "" : formatValue(c, v, opts) || "–", _kind: "sub" };
        });
      }
      return idx.map((i) => {
        const c = cols[i];
        const content = isNumericCol(c) ? formatValue(c, rawValue(c, it.row), opts) || "–" : String(cellPlain(c, it.row) ?? "");
        return it.extra === "total" ? { content, _kind: "sub" } : content;
      });
    });

  const headFor = (idx) => {
    const groups = [];
    idx.forEach((i, k) => {
      const g = k < model.pinnedCount || i < model.pinnedCount ? null : model.groupOf(cols[i].key);
      const last = groups[groups.length - 1];
      if (last && last.g === g && g) last.span++;
      else groups.push({ g, span: 1, i });
    });
    const anyBand = groups.some((x) => x.g);
    if (!anyBand) return [idx.map((i) => cols[i].exportHeader || cols[i].headerName)];
    const row1 = [];
    const row2 = [];
    groups.forEach((x) => {
      if (x.g) {
        row1.push({ content: x.g.label.toUpperCase(), colSpan: x.span, styles: { halign: "center" } });
        for (let k = 0; k < x.span; k++) row2.push(cols[idx[idx.indexOf(x.i) + k]].headerName);
      } else {
        for (let k = 0; k < x.span; k++) row1.push({ content: cols[idx[idx.indexOf(x.i) + k]].headerName, rowSpan: 2 });
      }
    });
    return [row1, row2];
  };

  const footFor = (idx) =>
    model.hasTotals
      ? [idx.map((i, k) => (k === 0 ? "TOTAL" : model.totals[cols[i].key] === undefined ? "" : formatValue(cols[i], model.totals[cols[i].key], opts) || "–"))]
      : undefined;

  const filtersText = (meta.filters || []).map((f) => `${f.label}: ${f.value}`).join("   ·   ");

  sets.forEach((idx, si) => {
    if (si > 0) doc.addPage(format, orientation);
    banner();
    let y = 20;
    doc.setTextColor(60, 60, 60);
    doc.setFontSize(7.5);
    if (filtersText) {
      const lines = doc.splitTextToSize(filtersText, avail);
      doc.text(lines, margin, y);
      y += lines.length * 3.4 + 1;
    }
    if (sets.length > 1) {
      doc.setFont("helvetica", "bold");
      doc.text(`Columns, part ${si + 1} of ${sets.length} (pinned columns repeat)`, margin, y);
      doc.setFont("helvetica", "normal");
      y += 4;
    }
    const columnStyles = {};
    // Spread the set over the page width (it was chosen to fit at pt).
    const scale = avail / idx.reduce((a, i) => a + widthAt(pt, i), 0);
    idx.forEach((i, k) => {
      columnStyles[k] = { cellWidth: widthAt(pt, i) * scale, halign: isNumericCol(cols[i]) ? "right" : "left" };
    });
    autoTable(doc, {
      head: headFor(idx),
      body: bodyFor(idx),
      foot: footFor(idx),
      showFoot: "lastPage",
      showHead: "everyPage",
      startY: y,
      margin: { left: margin, right: margin, top: 18, bottom: 10 },
      styles: { font: "helvetica", fontSize: pt, cellPadding: { top: 1.2, bottom: 1.2, left: 1.2, right: 1.2 }, lineWidth: 0.1, lineColor: [225, 215, 213], overflow: "linebreak", textColor: [35, 26, 25] },
      headStyles: { fillColor: MAROON_RGB, textColor: [255, 255, 255], fontStyle: "bold", fontSize: pt },
      footStyles: { fillColor: [246, 240, 239], textColor: [35, 26, 25], fontStyle: "bold", fontSize: pt },
      alternateRowStyles: { fillColor: [251, 248, 247] },
      columnStyles,
      didParseCell: (h) => {
        if (h.section === "foot" && isNumericCol(cols[idx[h.column.index]])) h.cell.styles.halign = "right";
        if (h.section !== "body") return;
        const kind = h.cell.raw?._kind;
        const col = cols[idx[h.column.index]];
        if (!kind && col && isNumericCol(col) && isBoldNumber(col)) h.cell.styles.fontStyle = "bold";
        if (kind === "group") {
          h.cell.styles.fillColor = [247, 236, 236];
          h.cell.styles.textColor = MAROON_RGB;
          h.cell.styles.fontStyle = "bold";
        } else if (kind === "sub") {
          h.cell.styles.fillColor = [241, 241, 241];
          h.cell.styles.fontStyle = "bold";
        }
      },
      didDrawPage: () => banner(),
    });
  });

  const pages = doc.internal.getNumberOfPages();
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i);
    const ph = doc.internal.pageSize.getHeight();
    doc.setFontSize(7);
    doc.setTextColor(110, 98, 96);
    doc.text(meta.companyName || "", margin, ph - 4);
    doc.text(`Page ${i} of ${pages}`, pageW - margin, ph - 4, { align: "right" });
  }
  return doc;
}
